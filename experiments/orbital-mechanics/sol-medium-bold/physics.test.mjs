import assert from 'node:assert/strict';
import {MU,EARTH,circular,advance,impulse,elements,forecast,hohmann} from './physics.js';
const measurements=[];
function check(name,value,tolerance){assert.ok(Math.abs(value)<=tolerance,`${name}: ${value} exceeds ${tolerance}`);measurements.push({name,value,tolerance,pass:true});}
const initial=circular(400),e0=elements(initial),period=2*Math.PI*Math.sqrt((EARTH+400)**3/MU);
const once=advance(initial,period);
check('One circular revolution position error / km',Math.hypot(once[0]-initial[0],once[1]-initial[1]),.0001);
check('One circular revolution velocity error / km/s',Math.hypot(once[2]-initial[2],once[3]-initial[3]),.000001);
const ten=advance(initial,period*10),e10=elements(ten);
check('Ten revolutions relative specific-energy drift',(e10.energy-e0.energy)/e0.energy,1e-8);
check('Ten revolutions relative angular-momentum drift',(e10.h-e0.h)/e0.h,1e-8);
const radial=impulse(initial,0,100),along=impulse(initial,100,0);
check('Radial impulse x velocity change / km/s',radial[2]-initial[2]-.1,1e-12);
check('Tangential impulse y velocity change / km/s',along[3]-initial[3]-.1,1e-12);
const quarter=circular(400,90),rotated=impulse(quarter,100,50);
check('Rotated local-frame tangential impulse / km/s',rotated[2]-quarter[2]+.1,1e-12);
check('Rotated local-frame radial impulse / km/s',rotated[3]-quarter[3]-.05,1e-12);
const p=hohmann(400,800,12),r=forecast({burns:p.burns,duration:p.burns[1].time+600});
check('Phased Hohmann rendezvous separation / km',r.closest.distance,.001);
check('Phased Hohmann rendezvous relative speed / m/s',r.closest.relative,.001);
const arrival=r.rows.find(row=>Math.abs(row.time-p.burns[1].time)<1e-8);
assert.ok(arrival);
check('Rendezvous separation at exact circularization event / km',arrival.distance,.001);
check('Relative speed at exact circularization event / m/s',arrival.relative,.001);
check('Post-transfer circular altitude error / km',Math.hypot(...r.rows.at(-1).tug.slice(0,2))-(EARTH+800),.001);
check('Post-transfer circular eccentricity',elements(r.rows.at(-1).tug).e,1e-7);
assert.equal(r.impact,null);measurements.push({name:'Hohmann has no impact',value:r.impact,pass:true});
const fractional=forecast({burns:[{time:13.125,tangential:120,radial:-20}],duration:30});
const event=fractional.rows.find(row=>row.time===13.125);assert.ok(event,'Exact fractional burn event recorded');
const expected=impulse(advance(initial,13.125),120,-20);
check('Fractional burn event state error',Math.max(...event.tug.map((v,i)=>Math.abs(v-expected[i]))),1e-8);
const ground=forecast({burns:[{time:0,tangential:-1500,radial:0},{time:3000,tangential:2000,radial:0}],duration:5000});
assert.ok(ground.impact!==null&&ground.impact<3000);assert.deepEqual(ground.rows.at(-1).tug,ground.rows.find(row=>row.impact).tug);measurements.push({name:'Impact detected; post-impact tug frozen and later impulse ignored',value:ground.impact,units:'seconds',pass:true});
assert.ok(!Number.isFinite(elements(impulse(initial,5000,0)).apo));measurements.push({name:'Escape impulse classified as unbound',pass:true});
console.log(JSON.stringify({checks:measurements.length,measurements,planner:{wait:p.wait,transfer:p.transfer,deltaV:r.deltaV,meetingTime:r.closest.time}},null,2));
