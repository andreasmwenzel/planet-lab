import assert from 'node:assert/strict';
import {EARTH,MU,mag,circular,step,elements,burn,circularize,hohmann,trajectory,nextApsis} from './physics.js';
const results=[];
function close(name,value,expected,tolerance){const error=Math.abs(value-expected);assert.ok(error<=tolerance,`${name}: ${value}, expected ${expected} ± ${tolerance}`);results.push({name,value,expected,absoluteError:error,tolerance});}
const initial=circular(400),ie=elements(initial);
close('400 km circular velocity (km/s)',ie.v,Math.sqrt(MU/(EARTH+400)),1e-12);
close('Circular eccentricity',ie.e,0,1e-12);
const returned=step(initial,ie.period);
close('Circular one-period position closure (km)',mag(returned.r.map((v,i)=>v-initial.r[i])),0,.001);
close('Circular one-period velocity closure (km/s)',mag(returned.v.map((v,i)=>v-initial.v[i])),0,.000001);
const elliptic=burn(initial,0,.8),ee=elements(elliptic),after=step(elliptic,ee.period*3),ae=elements(after);
close('Elliptic three-period relative energy drift',Math.abs((ae.energy-ee.energy)/ee.energy),0,1e-8);
close('Elliptic three-period relative angular-momentum drift',Math.abs((ae.h-ee.h)/ee.h),0,1e-8);
close('Elliptic three-period position closure (km)',mag(after.r.map((v,i)=>v-elliptic.r[i])),0,.01);
const plan=hohmann(EARTH+400,EARTH+1200),transfer=burn(initial,0,plan.first),te=elements(transfer);
close('Hohmann periapsis altitude (km)',te.rp-EARTH,400,1e-8);
close('Hohmann apoapsis altitude (km)',te.ra-EARTH,1200,1e-8);
close('Next apsis time matches Hohmann half-period (s)',nextApsis(transfer).time,plan.time,1e-8);
assert.equal(nextApsis(initial),null);results.push({name:'Circular orbit has no unique apsis target',passed:true});
const top=step(transfer,plan.time);
close('Propagated Hohmann target altitude (km)',mag(top.r)-EARTH,1200,.001);
close('Hohmann arrival radial velocity (km/s)',elements(top).radial,0,1e-6);
close('Next apsis from apoapsis targets periapsis (s)',nextApsis(top).time,plan.time,.001);
assert.equal(nextApsis(top).name,'periapsis');results.push({name:'Next apsis correctly switches at apoapsis',passed:true});
const final=burn(top,0,plan.second),fe=elements(final);
close('Hohmann final eccentricity',fe.e,0,1e-6);
close('Hohmann final semimajor axis (km)',fe.a,EARTH+1200,.001);
const tilted=burn(step(initial,ie.period/4),.25,-.1),ti=elements(tilted),ci=circularize(tilted),c=elements(burn(tilted,ci.radial,ci.tangential));
close('Circularization cancels radial velocity',c.radial,0,1e-12);
close('Circularization final eccentricity',c.e,0,1e-12);
close('Local radial burn component',ti.radial,.25,1e-7);
close('Local prograde burn component',ti.tangential,ie.v-.1,1e-7);
assert.ok(elements(burn(initial,0,4)).energy>0);results.push({name:'4 km/s prograde burn creates unbound orbit',passed:true});
const crash=burn(initial,0,-.5);assert.ok(elements(crash).rp<EARTH);assert.equal(trajectory(crash).impact,true);results.push({name:'Retrograde collision predicted and surface propagation stopped',passed:true});
const unchanged=step(initial,0);assert.deepEqual(unchanged,initial);assert.notEqual(unchanged.r,initial.r);results.push({name:'Zero-time propagation preserves state without aliasing',passed:true});
assert.deepEqual(initial,circular(400));results.push({name:'Original input state remains immutable',passed:true});
console.log(JSON.stringify({status:'PASS',checks:results.length,results},null,2));
